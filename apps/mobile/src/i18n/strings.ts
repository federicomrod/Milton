export type Language = "es" | "en" | "de";
export const DICTIONARIES: Record<Language, Strings> = { es, en, de };

/** «Hola, {name}» + { name: "Luis" } -> «Hola, Luis». */
export function fmt(
  template: string,
  vars: Record<string, string | number> = {}
): string {
  return template.replace(/\{(\w+)\}/g, (m, key: string) =>
    key in vars ? String(vars[key]) : m
  );
}

/** Device language -> one of ours; anything else is Spanish. */
export function languageOf(code: string | null | undefined): Language {
  const base = (code ?? "").toLowerCase().split("-")[0];
  return base === "de" || base === "en" ? base : "es";
}
